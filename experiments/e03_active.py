"""E3: does active sampling help at a fixed survey budget?

Simulator, full response (the design decides who is surveyed), configs/e03_active.yaml.
For each labeler signal strength and survey budget n, four designs are compared, each
with its natural estimator:

- ``uniform`` -> ``ppi`` (the reference);
- ``stratified_proportional`` and ``stratified_neyman`` -> ``ppi_stratified``;
- ``active`` (Poisson, pi proportional to the predicted NPS sd, 0.1 uniform floor) ->
  ``ppi_active``.

Criterion A4 (docs/PLAN.md): the active design's intervals are narrower than uniform
sampling's at an equal (expected) budget, with coverage still meeting A1. The table
reports, against the uniform reference at the same signal and n:

- ``width_gain`` = (reference mean width / design mean width)^2, the effective-n gain;
- ``mse_gain`` = MSE_reference / MSE_design.

Usage::

    uv run python experiments/e03_active.py [--replicates R]
"""

from __future__ import annotations

import argparse
import dataclasses
import time
from collections.abc import Sequence
from pathlib import Path

import polars as pl

from silent97.eval import harness, metrics
from silent97.viz import figures

NATURAL = {
    "uniform": "ppi",
    "stratified_proportional": "ppi_stratified",
    "stratified_neyman": "ppi_stratified",
    "active": "ppi_active",
}


def a4_table(results: pl.DataFrame, cfg: harness.GridConfig) -> pl.DataFrame:
    """One row per (signal, n, design) with its natural estimator and gains vs uniform."""
    info = pl.DataFrame(
        {
            "scenario": [s.name for s in cfg.scenarios],
            "design": [s.design for s in cfg.scenarios],
            "signal": [float(s.signal_strength or 0.0) for s in cfg.scenarios],
        }
    )
    natural = pl.DataFrame({"design": list(NATURAL), "estimator": list(NATURAL.values())})
    keep = results.join(info, on="scenario").join(natural, on=["design", "estimator"])
    err = pl.col("point") - pl.col("truth")
    t = keep.group_by("signal", "n_labeled", "design", "estimator").agg(
        pl.len().alias("replicates"),
        pl.col("covered").sum().alias("n_covered"),
        pl.col("width").mean().alias("mean_width"),
        (err**2).mean().alias("mse"),
        err.mean().alias("bias"),
        pl.col("n_realized").mean().alias("mean_n_realized"),
        pl.col("model_corr").first().alias("model_corr"),
    )
    bounds = [
        metrics.wilson_interval(int(k), int(r))
        for k, r in zip(t["n_covered"], t["replicates"], strict=True)
    ]
    t = t.with_columns(
        (pl.col("n_covered") / pl.col("replicates")).alias("coverage"),
        pl.Series("coverage_lo", [b[0] for b in bounds]),
        pl.Series("coverage_hi", [b[1] for b in bounds]),
    ).with_columns(
        pl.struct("coverage_lo", "coverage_hi")
        .map_elements(
            lambda r: metrics.overlaps_target(r["coverage_lo"], r["coverage_hi"]),
            return_dtype=pl.Boolean,
        )
        .alias("coverage_ok")
    )
    ref = t.filter(pl.col("design") == "uniform").select(
        "signal", "n_labeled", pl.col("mean_width").alias("_w"), pl.col("mse").alias("_m")
    )
    t = t.join(ref, on=["signal", "n_labeled"], how="left").with_columns(
        ((pl.col("_w") / pl.col("mean_width")) ** 2).alias("width_gain"),
        (pl.col("_m") / pl.col("mse")).alias("mse_gain"),
    )
    order = {d: i for i, d in enumerate(NATURAL)}
    return (
        t.drop("_w", "_m")
        .with_columns(pl.col("design").replace_strict(order).alias("_o"))
        .sort("signal", "n_labeled", "_o")
        .drop("_o")
    )


def markdown(t: pl.DataFrame, cfg: harness.GridConfig) -> str:
    lines = [
        f"# {cfg.name} summary\n",
        f"Generated by `experiments/e03_active.py` ({cfg.replicates} replicates, seed "
        f"{cfg.seed}). Each design with its natural estimator; gains vs uniform + PPI at "
        "the same signal and n. A4: active narrower than uniform with coverage in the A1 "
        "band.\n",
        "| signal (ρ) | n | design → estimator | realized n | coverage [Wilson 95%] | in A1 "
        "| mean width | width gain | MSE gain | bias |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in t.iter_rows(named=True):
        lines.append(
            f"| {r['signal']:.2f} ({r['model_corr']:.2f}) | {r['n_labeled']} | {r['design']} → "
            f"{r['estimator']} | {r['mean_n_realized']:.1f} | {r['coverage']:.3f} "
            f"[{r['coverage_lo']:.3f}, {r['coverage_hi']:.3f}] | "
            f"{'yes' if r['coverage_ok'] else 'NO'} | {r['mean_width']:.2f} | "
            f"{r['width_gain']:.3f} | {r['mse_gain']:.3f} | {r['bias']:+.2f} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="E3: sampling designs at equal budget")
    parser.add_argument("--config", default="configs/e03_active.yaml")
    parser.add_argument("--replicates", type=int, default=None)
    parser.add_argument("--results-dir", default="data/results")
    parser.add_argument("--docs-dir", default="docs/results")
    args = parser.parse_args(argv)
    cfg = harness.load_grid_config(args.config)
    if args.replicates is not None:
        cfg = dataclasses.replace(cfg, replicates=args.replicates)
    start = time.perf_counter()
    results = harness.run_grid(cfg)
    raw = harness.write_results(results, Path(args.results_dir) / f"{cfg.name}.parquet")
    t = a4_table(results, cfg)
    docs = Path(args.docs_dir)
    docs.mkdir(parents=True, exist_ok=True)
    t.write_csv(docs / f"{cfg.name}_summary.csv", float_precision=6)
    text = markdown(t, cfg)
    (docs / f"{cfg.name}_summary.md").write_text(text)
    figures.design_figure(
        t, docs / f"{cfg.name}.png", nominal=1 - cfg.alpha,
        title="E3: sampling designs at equal survey budget (simulator, full response)",
    )  # fmt: skip
    print(text)
    print(f"{results.height} rows in {time.perf_counter() - start:.0f} s -> {raw}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
