"""E4: what happens under realistic nonresponse?

Simulator, self-selected respondents (the scenario's response propensities), MAR and
MNAR (configs/e04_nonresponse.yaml). Estimators:

- ``classical`` on respondents (the naive respondent NPS);
- ``naive_model`` (model-only);
- ``ppi_pp_cf`` (PPI++, the small-survey default);
- ``mrp`` and ``mrp_ppi`` (province x age x tenure cells; Laplace fit).

Under MAR the response depends on observed traits only. MRP corrects the part carried
by its cells; the rest of the MAR mechanism (digital engagement, complaints) is not in
the cells. Under MNAR it also depends on satisfaction itself, which no method here can
correct (E7's sensitivity analysis bounds it).

``--nuts-check R`` reruns ``mrp`` and ``mrp_ppi`` with NUTS on the first R replicates
of one setting (the same survey draws) and reports the agreement with Laplace
(CLAUDE.md rule 7).

Usage::

    uv run python experiments/e04_nonresponse.py [--replicates R] [--nuts-check 30]
"""

from __future__ import annotations

import argparse
import dataclasses
import time
from collections.abc import Sequence
from pathlib import Path

import polars as pl

from silent97.eval import harness, metrics
from silent97.viz import figures


def nuts_agreement(laplace: pl.DataFrame, nuts: pl.DataFrame) -> pl.DataFrame:
    """Per estimator: NUTS minus Laplace on the same draws, in units of the Laplace se."""
    keys = ["scenario", "n_labeled", "replicate", "estimator"]
    cols = ["point", "lower", "upper", "se", "covered"]
    j = laplace.select(*keys, *cols).join(nuts.select(*keys, *cols), on=keys, suffix="_nuts")
    return (
        j.with_columns(
            ((pl.col("point_nuts") - pl.col("point")) / pl.col("se")).alias("d_point"),
            ((pl.col("lower_nuts") - pl.col("lower")) / pl.col("se")).alias("d_lower"),
            ((pl.col("upper_nuts") - pl.col("upper")) / pl.col("se")).alias("d_upper"),
            (pl.col("se_nuts") / pl.col("se")).alias("se_ratio"),
        )
        .group_by("scenario", "n_labeled", "estimator")
        .agg(
            pl.len().alias("replicates"),
            pl.col("d_point").mean().alias("mean_d_point"),
            pl.col("d_point").abs().max().alias("max_abs_d_point"),
            pl.col("d_lower").abs().max().alias("max_abs_d_lower"),
            pl.col("d_upper").abs().max().alias("max_abs_d_upper"),
            pl.col("se_ratio").mean().alias("mean_se_ratio"),
            (pl.col("covered") == pl.col("covered_nuts")).mean().alias("same_coverage_call"),
        )
        .sort("estimator")
    )


def markdown(summary: pl.DataFrame, cfg: harness.GridConfig) -> str:
    lines = [
        f"# {cfg.name} summary\n",
        f"Generated by `experiments/e04_nonresponse.py` ({cfg.replicates} replicates, seed "
        f"{cfg.seed}, MRP fit: {cfg.mrp_fit}). Self-selected respondents; truth = pool NPS. "
        "Widths, bias and RMSE in NPS points.\n",
        "| scenario | estimator | n | coverage [Wilson 95%] | in A1 | mean width | bias | RMSE |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in summary.sort("scenario", "n_labeled", "estimator").iter_rows(named=True):
        lines.append(
            f"| {r['scenario']} | {r['estimator']} | {r['n_labeled']} | {r['coverage']:.3f} "
            f"[{r['coverage_lo']:.3f}, {r['coverage_hi']:.3f}] | "
            f"{'yes' if r['coverage_ok'] else 'NO'} | {r['mean_width']:.2f} | "
            f"{r['bias']:+.2f} | {r['rmse']:.2f} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="E4: nonresponse (MAR, MNAR)")
    parser.add_argument("--config", default="configs/e04_nonresponse.yaml")
    parser.add_argument("--replicates", type=int, default=None)
    parser.add_argument("--nuts-check", type=int, default=0, help="replicates for NUTS vs Laplace")
    parser.add_argument("--nuts-scenario", default="mar")
    parser.add_argument("--nuts-n", type=int, default=500)
    parser.add_argument("--results-dir", default="data/results")
    parser.add_argument("--docs-dir", default="docs/results")
    args = parser.parse_args(argv)
    cfg = harness.load_grid_config(args.config)
    if args.replicates is not None:
        cfg = dataclasses.replace(cfg, replicates=args.replicates)
    docs = Path(args.docs_dir)
    docs.mkdir(parents=True, exist_ok=True)
    start = time.perf_counter()
    if args.nuts_check:
        sub = dataclasses.replace(
            cfg,
            name=f"{cfg.name}_nuts_check",
            scenarios=tuple(s for s in cfg.scenarios if s.name == args.nuts_scenario),
            estimators=("mrp", "mrp_ppi"),
            n_labeled=(args.nuts_n,),
            replicates=args.nuts_check,
        )
        lap = harness.run_grid(sub)
        nuts = harness.run_grid(dataclasses.replace(sub, mrp_fit="nuts"))
        table = nuts_agreement(lap, nuts)
        table.write_csv(docs / f"{sub.name}.csv", float_precision=6)
        print(table)
        print(f"NUTS check in {time.perf_counter() - start:.0f} s")
        return 0
    results = harness.run_grid(cfg)
    raw = harness.write_results(results, Path(args.results_dir) / f"{cfg.name}.parquet")
    summary = metrics.summarize(results)
    summary.write_csv(docs / f"{cfg.name}_summary.csv", float_precision=6)
    text = markdown(summary, cfg)
    (docs / f"{cfg.name}_summary.md").write_text(text)
    for s in cfg.scenarios:
        figures.coverage_figure(
            summary.filter(pl.col("scenario") == s.name),
            docs / f"{cfg.name}_{s.name}.png",
            nominal=1 - cfg.alpha,
            title=f"E4: self-selected respondents, {s.mechanism.upper()} (simulator)",
            width_label="mean interval width (NPS points, log scale)",
        )
    print(text)
    print(f"{results.height} rows in {time.perf_counter() - start:.0f} s -> {raw}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
