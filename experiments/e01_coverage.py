"""E1: do intervals keep their promise?

Simulator, MCAR, all Phase 2 estimators, n in {50, 100, 200, 500, 1000}, 1,000
replicates, nominal 90% intervals (docs/PLAN.md, Experiments).

Usage::

    uv run python experiments/e01_coverage.py [--config configs/e01_coverage.yaml]
        [--replicates R] [--n-jobs J]

Writes the per-replicate results to ``data/results/e01_coverage.parquet``
(git-ignored), and the summary table (CSV and Markdown) and figure to
``docs/results/``.
"""

from __future__ import annotations

import argparse
import dataclasses
import time
from collections.abc import Sequence
from pathlib import Path

import polars as pl

from silent97.eval import harness, metrics
from silent97.viz import figures

SUMMARY_COLUMNS = [
    "scenario", "estimator", "n_labeled", "replicates", "coverage", "coverage_lo",
    "coverage_hi", "coverage_ok", "mean_width", "bias", "rmse", "mean_se",
    "mean_lambda", "effective_n", "responses_saved",
]  # fmt: skip


def markdown_table(summary: pl.DataFrame) -> str:
    """Render the summary as a Markdown table (the figure's table view)."""
    header = (
        "| estimator | n | coverage | Wilson 95% | within A1 | mean width | bias | RMSE | "
        "mean λ | effective n |\n|---|---|---|---|---|---|---|---|---|---|\n"
    )
    lines = []
    for r in summary.iter_rows(named=True):
        lam = "" if r["mean_lambda"] is None else f"{r['mean_lambda']:.3f}"
        lines.append(
            f"| {r['estimator']} | {r['n_labeled']} | {r['coverage']:.3f} | "
            f"[{r['coverage_lo']:.3f}, {r['coverage_hi']:.3f}] | "
            f"{'yes' if r['coverage_ok'] else 'NO'} | {r['mean_width']:.2f} | "
            f"{r['bias']:+.2f} | {r['rmse']:.2f} | {lam} | {r['effective_n']:.0f} |"
        )
    return header + "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="E1: coverage of nominal 90% intervals")
    parser.add_argument("--config", default="configs/e01_coverage.yaml")
    parser.add_argument("--replicates", type=int, default=None, help="override (quick checks)")
    parser.add_argument("--n-jobs", type=int, default=None)
    parser.add_argument("--results-dir", default="data/results")
    parser.add_argument("--docs-dir", default="docs/results")
    args = parser.parse_args(argv)

    cfg = harness.load_grid_config(args.config)
    if args.replicates is not None:
        cfg = dataclasses.replace(cfg, replicates=args.replicates)
    if args.n_jobs is not None:
        cfg = dataclasses.replace(cfg, n_jobs=args.n_jobs)
    suffix = "" if args.replicates is None else f"_r{cfg.replicates}"

    start = time.perf_counter()
    results = harness.run_grid(cfg)
    elapsed = time.perf_counter() - start
    raw = harness.write_results(results, Path(args.results_dir) / f"{cfg.name}{suffix}.parquet")

    summary = metrics.summarize(results).select(SUMMARY_COLUMNS)
    docs = Path(args.docs_dir)
    docs.mkdir(parents=True, exist_ok=True)
    summary.write_csv(docs / f"{cfg.name}{suffix}_summary.csv", float_precision=6)
    (docs / f"{cfg.name}{suffix}_summary.md").write_text(
        f"# {cfg.name} summary\n\nGenerated by `experiments/e01_coverage.py` from "
        f"`{args.config}` ({cfg.replicates} replicates, seed {cfg.seed}). "
        f"Truth: {results['truth'][0]:.4f}.\n\n" + markdown_table(summary)
    )
    fig = figures.coverage_figure(
        summary.filter(pl.col("scenario") == cfg.scenarios[0].name),
        docs / f"{cfg.name}{suffix}.png",
        nominal=1 - cfg.alpha,
        title=f"E1, MCAR, signal strength {cfg.scenarios[0].signal_strength}",
    )
    print(markdown_table(summary))
    print(f"{len(results)} rows in {elapsed:.0f} s -> {raw}, {fig}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
